#!/usr/bin/env node
/**
 * Generate TypeScript types from the live opencode OpenAPI document.
 * Prefers the running BFF (/api/oc/spec, no credentials needed by codegen),
 * falls back to docs/upstream/openapi-2.2.1.json.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const runtimeFile = path.join(process.env.LOCALAPPDATA ?? '', 'opencode-gui', 'runtime.json');
const outFile = path.join(root, 'packages', 'protocol', 'src', 'generated', 'openapi.d.ts');
const fallback = path.join(root, 'docs', 'upstream', 'openapi-2.2.1.json');

async function loadFromBff() {
  try {
    const runtime = JSON.parse(fs.readFileSync(runtimeFile, 'utf8'));
    const url = runtime?.bff?.url;
    if (!url) return null;
    const res = await fetch(url + '/api/oc/spec', { signal: AbortSignal.timeout(8000) });
    if (!res.ok) return null;
    return { spec: await res.json(), source: url + '/api/oc/spec' };
  } catch {
    return null;
  }
}

const live = await loadFromBff();
let spec;
let source;
if (live) {
  spec = live.spec;
  source = live.source;
} else {
  spec = JSON.parse(fs.readFileSync(fallback, 'utf8'));
  source = path.relative(root, fallback);
}

const ast = await openapiTS(spec);
const output = typeof ast === 'string' ? ast : astToString(ast);
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(
  outFile,
  `/* eslint-disable */\n/* Generated by scripts/codegen.mjs from the opencode OpenAPI document. Do not edit. */\n\n${output}`,
  'utf8',
);
console.log(`[codegen] ${source} -> ${path.relative(root, outFile)} (${output.length} bytes)`);
console.log('[codegen] CI check: git diff --exit-code packages/protocol/src/generated');
