export function translate(
  locale: string,
  custom: { strings: Record<string, string> } | null,
  key: string,
  fallback?: string,
): string {
  return custom?.strings?.[key] ?? MESSAGES[locale]?.[key] ?? MESSAGES.zh[key] ?? fallback ?? key;
}

export function useT() {
  const locale = useApp((s) => s.locale);
  const customLocale = useApp((s) => s.customLocale);
  return (key: string, fallback?: string) => translate(locale, customLocale, key, fallback);
}
